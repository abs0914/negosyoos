import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

import type { Business } from '@negosyo-os/business';
import type { Quotation } from './models';

const number = new Intl.NumberFormat('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
function money(value: number) {
    return `${value < 0 ? '-' : ''}PHP ${number.format(Math.abs(value))}`;
}
function safe(value: string) {
    return value.replace(/[^\x20-\x7E]/g, '-');
}

export async function renderQuotationPdf(quotation: Quotation, business: Business): Promise<Uint8Array> {
    const pdf = await PDFDocument.create();
    const regular = await pdf.embedFont(StandardFonts.Helvetica);
    const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
    const pageSize: [number, number] = [595.28, 841.89];
    let page = pdf.addPage(pageSize);
    let y = 790;
    const draw = (text: string, x: number, size = 10, font = regular, color = rgb(0.12, 0.15, 0.2)) =>
        page.drawText(safe(text), { x, y, size, font, color });
    const nextPage = () => {
        page = pdf.addPage(pageSize);
        y = 790;
    };
    page.drawRectangle({ x: 0, y: 750, width: 595.28, height: 91.89, color: rgb(0.08, 0.22, 0.36) });
    draw(business.tradeName, 42, 20, bold, rgb(1, 1, 1));
    y -= 30;
    draw('QUOTATION', 42, 11, bold, rgb(0.72, 0.87, 1));
    y = 716;
    draw(
        `${quotation.quotationNumber}${quotation.revisionNumber ? ` / REV ${quotation.revisionNumber}` : ''}`,
        42,
        15,
        bold
    );
    draw(`Valid until: ${quotation.validUntil}`, 390, 10);
    y -= 27;
    draw('Prepared for', 42, 8, bold, rgb(0.4, 0.45, 0.5));
    y -= 17;
    draw(quotation.customerName, 42, 13, bold);
    y -= 15;
    draw(
        [quotation.customerMobile, quotation.customerEmail].filter(Boolean).join(' | ') ||
            'Customer contact not provided',
        42,
        9
    );
    y -= 32;
    page.drawRectangle({ x: 36, y: y - 7, width: 523, height: 24, color: rgb(0.92, 0.95, 0.97) });
    draw('ITEM', 42, 9, bold);
    draw('QTY', 315, 9, bold);
    draw('PRICE', 365, 9, bold);
    draw('DISCOUNT', 430, 9, bold);
    draw('TOTAL', 510, 9, bold);
    y -= 28;
    for (const item of quotation.lines) {
        if (y < 150) {
            nextPage();
        }
        draw(
            `${item.productName}${item.variantName === 'Default' ? '' : ` - ${item.variantName}`} (${item.sku})`,
            42,
            9
        );
        draw(`${item.quantity} ${item.unit}`, 315, 9);
        draw(money(item.unitPrice), 365, 9);
        draw(money(item.discountAmount), 430, 9);
        draw(money(item.total), 490, 9, bold);
        y -= 24;
        page.drawLine({
            start: { x: 42, y: y + 12 },
            end: { x: 553, y: y + 12 },
            thickness: 0.4,
            color: rgb(0.82, 0.84, 0.86)
        });
    }
    y -= 14;
    const totals = [
        ['Subtotal', quotation.subtotal],
        ['Discount', -quotation.discountTotal],
        ['Tax', quotation.taxTotal]
    ] as const;
    for (const [label, value] of totals) {
        draw(label, 390, 10);
        draw(money(value), 480, 10);
        y -= 18;
    }
    y -= 10;
    page.drawRectangle({ x: 382, y: y - 7, width: 177, height: 31, color: rgb(0.08, 0.22, 0.36) });
    draw('TOTAL', 392, 12, bold, rgb(1, 1, 1));
    draw(money(quotation.total), 455, 12, bold, rgb(1, 1, 1));
    y -= 48;
    if (quotation.notes) {
        draw('NOTES', 42, 9, bold);
        y -= 16;
        for (const part of quotation.notes.match(/.{1,92}(?:\s|$)/g) ?? [quotation.notes]) {
            draw(part.trim(), 42, 9);
            y -= 13;
        }
        y -= 10;
    }
    if (quotation.terms) {
        draw('TERMS', 42, 9, bold);
        y -= 16;
        for (const part of quotation.terms.match(/.{1,92}(?:\s|$)/g) ?? [quotation.terms]) {
            if (y < 55) nextPage();
            draw(part.trim(), 42, 9);
            y -= 13;
        }
    }
    for (const [index, pdfPage] of pdf.getPages().entries())
        pdfPage.drawText(`Generated by NegosyoOS | Page ${index + 1} of ${pdf.getPageCount()}`, {
            x: 42,
            y: 25,
            size: 8,
            font: regular,
            color: rgb(0.45, 0.48, 0.52)
        });
    return pdf.save();
}
